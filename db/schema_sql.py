"""Render db/schema.sql (Postgres + pgvector DDL) from db/models.py.  python -m db.schema_sql"""
from __future__ import annotations

from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable

from .models import Base

PATH = Path(__file__).with_name("schema.sql")
HEADER = ("-- GENERATED by `python -m db.schema_sql` from db/models.py. Do not edit by hand.\n"
          "-- Postgres 16 + pgvector. The loaders create the same tables via SQLAlchemy.\n\n"
          "CREATE EXTENSION IF NOT EXISTS vector;\n")


def render() -> str:
    d = postgresql.dialect()
    parts = [HEADER]
    for t in Base.metadata.sorted_tables:
        parts.append(str(CreateTable(t).compile(dialect=d)).strip() + ";\n")
    parts.append("CREATE INDEX IF NOT EXISTS doc_chunk_embedding_hnsw ON doc_chunk "
                 "USING hnsw (embedding vector_cosine_ops);\n")
    return "\n".join(parts)


if __name__ == "__main__":
    PATH.write_text(render(), encoding="utf-8")
    print(f"wrote {PATH}")
